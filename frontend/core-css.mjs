import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFile } from 'node:fs/promises';
import { join } from 'node:path';
import postcss from 'postcss';

export const coreParts = ['vendor/bootstrap3.css', 'theme/ajenti.css'];
export const sha256 = text => createHash('sha256').update(text).digest('hex');
const significant = node => (node.nodes ?? []).filter(child => child.type !== 'comment');
const group = node => node.type === 'atrule' && node.nodes?.some(child => ['rule', 'atrule'].includes(child.type));
const heading = node => ({ name: node.name, params: node.params });
// PostCSS's comma splitter respects strings and parentheses. Do not normalize
// declaration values: strings, URLs and fallback declaration order are material.
const selector = node => node.type === 'rule' ? postcss.list.comma(node.selector).map(s => s.trim()).join(',') : `@${node.name} ${node.params}`.trim();
const declarations = node => significant(node).map(child => [child.prop, child.value, !!child.important]);
const identity = (node, context) => JSON.stringify([context, selector(node), declarations(node)]);

function leaves(root, context = []) {
    return significant(root).flatMap(node => group(node) ? leaves(node, [...context, heading(node)]) : [{ node, context }]);
}

/** Flatten grouping at-rules, retaining their full context and leaf rule order. */
export function normalizedRules(css) {
    return leaves(postcss.parse(css)).map(({ node, context }) => JSON.parse(identity(node, context)));
}

/** Generate both pure CSS inputs and the original ordering; never hand-edit these. */
export function splitCoreCss(core, reference) {
    const upstream = leaves(postcss.parse(reference));
    const originals = leaves(postcss.parse(core));
    const exact = new Set(upstream.map(({ node, context }) => identity(node, context)));
    const peers = Map.groupBy(upstream, ({ node, context }) => JSON.stringify([context, selector(node)]));
    const partOf = (node, context) => exact.has(identity(node, context)) ? 'bootstrap' : 'theme';
    const sourceOf = part => coreParts[part === 'bootstrap' ? 0 : 1];
    const license = {
        bootstrap: 'Bootstrap 3.3.7 subset, MIT; see vendor/BOOTSTRAP-LICENSE.',
        theme: 'Ajenti theme from ajenti.plugin.core 0.116, MIT; see vendor/AJENTI-LICENSE.',
    };
    let files = Object.fromEntries(Object.entries(license).map(([part, notice]) => [sourceOf(part),
        `/*! ${notice}\n * Generated by split-core-css.mjs from pinned vendor/core.css; see theme/core-order.json.\n */\n`]));
    const lineAt = offset => core.slice(0, offset).split('\n').length;
    function segment(start, end, part, context) {
        const source = sourceOf(part), body = core.slice(start, end);
        // Wrappers make each source independently valid CSS. Only the body is
        // consumed by A1; the manifest retains the original grouping verbatim.
        const open = context.map(c => `@${c.name} ${c.params} {\n`).join('');
        const close = context.map(() => '\n}').join('');
        const from = files[source].length + open.length;
        files = { ...files, [source]: files[source] + open + body + close + '\n' };
        return { source, offsets: [from, from + body.length], coreLines: [lineAt(start), lineAt(end - 1)], sha256: sha256(body) };
    }
    function partition(root, start, end, context = []) {
        const nodes = significant(root);
        let cursor = start;
        const segments = [];
        for (let i = 0; i < nodes.length; i++) {
            const node = nodes[i];
            if (group(node)) {
                // These pinned grouping at-rules are @media/@keyframes; their
                // preludes contain no quoted braces. Keep their exact bytes.
                const inside = core.indexOf('{', node.source.start.offset) + 1;
                const finish = node.source.end.offset - 1;
                segments.push({ open: core.slice(cursor, inside),
                    ...partition(node, inside, finish, [...context, heading(node)]),
                    close: core.slice(finish, finish + 1), coreLines: [lineAt(cursor), lineAt(finish)] });
                cursor = finish + 1;
            } else {
                const part = partOf(node, context);
                while (i + 1 < nodes.length && !group(nodes[i + 1]) && partOf(nodes[i + 1], context) === part) i++;
                const finish = nodes[i].source.end.offset;
                segments.push(segment(cursor, finish, part, context));
                cursor = finish;
            }
        }
        return { segments, tail: core.slice(cursor, end) };
    }
    const manifest = { version: 1, offsets: 'UTF-16 code units; end exclusive',
        original: { source: 'vendor/core.css', sha256: sha256(core) },
        reference: { package: 'bootstrap@3.3.7', source: 'dist/css/bootstrap.css', sha256: sha256(reference) },
        ...partition(postcss.parse(core), 0, core.length) };
    const inventory = originals.map(({ node, context }) => ({
        line: node.source.start.line, endLine: node.source.end.line, context,
        selector: node.selector ?? selector(node), part: partOf(node, context),
        declarations: declarations(node),
        counterparts: (peers.get(JSON.stringify([context, selector(node)])) ?? []).map(ref => declarations(ref.node)),
    }));
    return { manifest, files, inventory };
}

/** Segment hashes catch stale inputs; final hash also catches order/duplication. */
export function assembleCoreCss(manifest, files) {
    assert.equal(manifest.version, 1, 'Unsupported core CSS manifest');
    function assemble(block) {
        return block.segments.map(segment => {
            if (segment.segments) return segment.open + assemble(segment) + segment.close;
            const body = files[segment.source]?.slice(...segment.offsets);
            assert.equal(typeof body, 'string', `Missing core CSS segment: ${segment.source}`);
            assert.equal(sha256(body), segment.sha256, `Changed core CSS segment: ${segment.source}:${segment.coreLines}`);
            return body;
        }).join('') + block.tail;
    }
    const css = assemble(manifest);
    assert.equal(sha256(css), manifest.original.sha256, 'Reassembled CSS differs from original');
    return css;
}

export async function loadCoreCss(frontend) {
    const manifest = JSON.parse(await readFile(join(frontend, 'theme/core-order.json'), 'utf8'));
    const files = Object.fromEntries(await Promise.all(coreParts.map(async source => [source, await readFile(join(frontend, source), 'utf8')])));
    return assembleCoreCss(manifest, files);
}
