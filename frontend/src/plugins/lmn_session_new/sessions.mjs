import { createValidation } from '../../common/validation.mjs';
const base = '/api/lmn/session';

// Angular filter:string searches all public scalar properties, including members.
function matches(value, query) {
    if (query.startsWith('!')) return !matches(value, query.slice(1));
    if (Array.isArray(value)) return value.some(item => matches(item, query));
    if (value && typeof value === 'object') return Object.entries(value).some(([key, item]) => !key.startsWith('$') && matches(item, query));
    return value !== undefined && value !== null && typeof value !== 'function' && String(value).toLowerCase().includes(query.toLowerCase());
}
export function visibleGroups(groups, query = '', sessions = false) {
    const rows = (groups ?? []).filter(group => matches(group, query));
    if (!sessions) return rows;
    // orderBy:'-name':true: ascending, but reversed input order for equal names.
    return rows.map((group, index) => ({ group, index })).sort((a, b) => {
        const x = typeof a.group.name === 'string' ? a.group.name.toLowerCase() : a.group.name;
        const y = typeof b.group.name === 'string' ? b.group.name.toLowerCase() : b.group.name;
        if (x === y) return b.index - a.index;
        if (typeof x !== typeof y) return typeof x < typeof y ? -1 : 1;
        return x < y ? -1 : 1;
    }).map(row => row.group).filter(group => matches(group, '!-autoGenerated'));
}

export function createSessions(aj) {
    const valid = createValidation(aj), t = aj.gettext;
    async function name(initial = '') {
        // The shared messagebox prompt already applies Angular ngTrim.
        const { value } = await aj.messagebox.prompt(t('Session Name'), initial);
        if (!value) return;
        const result = valid.isValidSession(value);
        if (result !== true) { aj.notify.error(t(result), undefined, { sticky: true }); return; }
        return value;
    }
    function selected(sid, title) {
        if (sid) return true;
        aj.messagebox.show({ title: t(title), text: t('You have to select a session first.'), positive: 'OK' });
        return false;
    }
    return {
        load: () => Promise.all(['schoolclasses', 'projects', 'sessions'].map(key => aj.http.get(`${base}/${key}`).then(r => r.data))),
        async new(members = []) {
            const value = await name(); if (!value) return;
            await aj.http.put(`${base}/sessions/${value}`, { members }); aj.notify.success(t('Session Created'));
        },
        async rename(sid, comment) {
            if (!selected(sid, 'No Session selected')) return;
            const value = await name(comment); if (!value) return;
            await aj.http.post(`${base}/sessions`, { action: 'rename-session', session: sid, comment: value });
            aj.notify.success(t('Session renamed')); return value;
        },
        async kill(sid, comment) {
            if (!selected(sid, 'No session selected')) return;
            await aj.messagebox.show({ text: t(`Delete Session: ${comment} ?`), positive: t('Delete'), negative: t('Cancel') });
            const { data } = await aj.http.delete(`${base}/sessions/${sid}`); aj.notify.success(t(data));
        },
    };
}
