<script setup>
import { computed, inject, onBeforeUnmount, ref, watch } from 'vue';
import { useSambaAccess } from '../../common/access.mjs';
import { getSessionStore } from './sessionStore.mjs';
import { createParticipants } from './participants.mjs';
import { createPolling } from './polling.mjs';
import { createSessions } from './sessions.mjs';
import Participants from './Participants.vue';
import SessionFiles from './SessionFiles.vue';
import { createTransfers } from './transfers.mjs';
const aj = inject('aj'), store = getSessionStore(aj), allowed = useSambaAccess(aj);
const api = createParticipants(aj, store), groups = createSessions(aj), menu = ref(false);
const transfers = createTransfers(aj, store, api);
const current = computed(() => store.state.current), ready = ref(false);
const room = createPolling(api.updateParticipants), files = createPolling(api.updateFileList);
let cleaned = false, offLeave = () => {};
const leave = () => !api.isCurrent() || !api.sessionChanged.value || window.confirm(aj.gettext('Do you really want to quit this session ? You can restart it later if you want.'));
function beforeUnload(event) {
    if (api.isCurrent() && api.sessionChanged.value) { event.preventDefault(); event.returnValue = 'Eventually not refreshing'; }
}
function cleanup() {
    if (cleaned) return;
    cleaned = true; api.dispose(); room.dispose(); files.dispose(); offLeave(); window.removeEventListener('beforeunload', beforeUnload);
    if (store.state.filePolling === files) store.state.filePolling = undefined;
}
onBeforeUnmount(cleanup);
// Original opens the workdir even for empty SID, before redirecting.
api.createWorkingDirectory(current.value.members).catch(() => { /* Existing HTTP interceptor owns errors. */ });
const kind = current.value.type === 'schoolclass' ? 'Schoolclass' : current.value.type === 'room' ? 'Room' : 'Group';
aj.pageTitle.set(aj.gettext('Session') + ' > ' + aj.gettext(kind) + ' ' + current.value.name);
if (store.enterDetail()) {
    ready.value = true; store.state.filePolling = files; offLeave = aj.guardLeave(leave); window.addEventListener('beforeunload', beforeUnload);
    if (current.value.type === 'room') room.start();
}
watch(() => aj.identity.user, () => { ready.value = false; cleanup(); aj.navigate('/view/lmn/sessionsList'); }, { flush: 'sync' });
const close = () => aj.navigate('/view/lmn/sessionsList');
async function action(fn) { menu.value = false; try { await fn(); } catch { /* Modal cancellation and HTTP errors are owned by the shell. */ } }
async function rename() {
    const name = await groups.rename(current.value.sid, current.value.name);
    if (api.isCurrent()) store.state.current = { ...current.value, name };
}
async function save(copy = false) {
    await groups.new(current.value.members.map(u => u.cn));
    if (!api.isCurrent()) return;
    if (!copy) api.sessionChanged.value = false;
    close();
}
async function kill() { await groups.kill(current.value.sid, current.value.name); if (api.isCurrent()) close(); }
</script>
<template>
    <br>
    <div v-if="ready && allowed">
        <Participants :store="store" :api="api" :files="files">
            <template #files="{ user }"><SessionFiles :store="store" :api="transfers" :user="user" /></template>
            <template #actions>
                <div v-if="!current.generated" class="input-group-btn" @focusout="event => { if (!event.currentTarget.contains(event.relatedTarget)) menu = false; }">
                    <button class="btn btn-default" :aria-expanded="menu" @click="menu = !menu">{{ aj.gettext('Edit group') }} <span class="caret"></span></button>
                    <ul v-show="menu" class="dropdown-menu dropdown-menu-right">
                        <li><a href="" data-rename @click.prevent="action(rename)">{{ aj.gettext('Rename group') }}</a></li>
                        <li><a href="" data-clone @click.prevent="action(() => save(true))">{{ aj.gettext('Duplicate group') }}</a></li>
                        <li><a href="" data-kill @click.prevent="action(kill)">{{ aj.gettext('Delete group') }}</a></li>
                    </ul>
                </div>
                <div v-else class="input-group-btn"><button data-save class="btn btn-default" @click="action(() => save())"><i class="fas fa-save"></i> {{ aj.gettext('Save group as') }}</button></div>
                <div v-if="current.name === 'this_room-autogenerated'" class="input-group-btn"><button data-room-toggle class="btn" :class="room.active.value ? 'btn-danger' : 'btn-success'" @click="room.active.value ? room.stop() : room.start()"><i class="fas fa-users"></i> {{ aj.gettext(room.active.value ? 'Stop autorefresh' : 'Start autorefresh') }}</button></div>
            </template>
        </Participants>
        <div class="floating-toolbar"><div class="button-group"><SessionFiles :store="store" :api="transfers" /><button data-close class="btn btn-lmn pull-right" @click="close">{{ aj.gettext('Close') }}</button></div></div>
    </div>
    <div v-else-if="ready" class="text-center root-access-blocker"><h1><i class="fas fa-exclamation-triangle"></i></h1><h4 class="alert alert-danger">{{ aj.gettext('You should not use WebUI as root user!') }}<br>{{ aj.gettext('If this is your first time running WebUI, proceed through the') }} <a href="/view/lmn/init/welcome">{{ aj.gettext('setup wizard') }}</a>.<br>{{ aj.gettext('Afterwards login using the global-admin account.') }}</h4></div>
</template>
